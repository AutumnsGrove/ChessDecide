/**
 * Regenerate `packages/render/src/pieces.ts` from the chessground piece CSS.
 * Run: pnpm exec tsx scripts/extract-pieces.ts
 * The output is committed: the renderer must never read CSS at runtime.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const cssPath = root + 'docs/mockups/vendor/chessground.cburnett.css';
const outPath = root + 'packages/render/src/pieces.ts';

const NAMES: Record<string, string> = { pawn: 'p', bishop: 'b', knight: 'n', rook: 'r', queen: 'q', king: 'k' };
const css = readFileSync(cssPath, 'utf8');
const pieces: Record<string, string> = {};

for (const m of css.matchAll(/piece\.(\w+)\.(white|black)\s*\{\s*background-image:\s*url\('data:image\/svg\+xml;base64,([^']+)'\)/g)) {
  const name = NAMES[m[1]!];
  if (!name) continue;
  pieces[m[2] === 'white' ? name.toUpperCase() : name] = Buffer.from(m[3]!, 'base64').toString('utf8');
}

const missing = [...'pnbrqkPNBRQK'].filter((k) => !pieces[k]);
if (missing.length) throw new Error(`could not extract pieces: ${missing.join(', ')}`);
for (const [key, svg] of Object.entries(pieces)) {
  if (!/^<svg[\s>]/.test(svg.trim())) throw new Error(`piece ${key} is not an SVG document`);
}

const body = `/** GENERATED by scripts/extract-pieces.ts from chessground.cburnett.css — do not edit by hand.
 *  Each value is one 45x45 piece SVG (white = uppercase key, black = lowercase). */
export const PIECES: Record<string, string> = ${JSON.stringify(pieces, null, 2)};
`;
writeFileSync(outPath, body);
console.log(`wrote ${Object.keys(pieces).length} pieces to ${outPath}`);
